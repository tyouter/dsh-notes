/**
 * Build the browser half from this directory's sources.
 *
 *   node build.mjs
 *
 * Three plain JavaScript bodies, concatenated in order:
 *
 *   src/head.js    the factory prologue: i18n, api helpers, formatting, styles
 *   src/board.js   the dashboard: charts, the stats view, the editor copilot
 *   src/panel.js   the panel: tabs, capture, history, the mount points
 *
 * `board.js` comes before `panel.js` because the panel renders the dashboard.
 * The output keeps the exact `window.__ModuleLoader__.load({ id, factory(require)
 * { … } })` shape a bundle's client half must have. It is a concatenation on
 * purpose: no bundler, no dependencies, and a diff in `client.js` still maps to a
 * single edit in one source file.
 */

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))

/** The loader id is the package name; read it so a rename cannot leave a stale id behind. */
async function readPackageName() {
  const manifest = JSON.parse(await readFile(join(here, 'package.json'), 'utf8'))
  return String(manifest.name ?? 'dsh-notes')
}

const PACKAGE = await readPackageName()

const header = `/**
 * Browser half of the notebook panel.
 *
 * GENERATED by build.mjs from src/head.js + src/board.js + src/panel.js — edit
 * those, not this.
 *
 * Renders into these slots: the sidebar icon (\`sidebar.panellist\`, whose list id
 * addresses the matching \`main\` panel), the panel body (\`main\`, keyed \`notes\`),
 * a capture control in the composer tool row (\`conversation.input.right\`), the
 * Alt+N shortcut (\`conversation.composer.dock\`) and the floating capture card
 * (\`shell.overlay\`). Data comes from this plugin's own host route at
 * \`/notes/api\`; nothing here imports a Harness client package, and every visual
 * value is a \`--dsw-alias-*\` theme token.
 */

window.__ModuleLoader__.load({
  id: '${PACKAGE}',
  factory(require) {
`

const footer = `
  },
})
`

const parts = ['head.js', 'board.js', 'panel.js']
const bodies = []
for (const name of parts) {
  const text = await readFile(join(here, 'src', name), 'utf8')
  bodies.push(text.trimEnd())
}

const body = `${bodies.join('\n\n')}\n`
const generated = header + body + footer
await writeFile(join(here, 'client.js'), generated, 'utf8')
console.log(`client.js written (${generated.length} bytes)`)
